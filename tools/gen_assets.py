#!/usr/bin/env python3
"""Helper for tools/gen-assets.sh: icon code points and the C++ emitter."""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def icons():
    cp = json.load(open(os.path.join(ROOT, "assets/fonts/lucide-codepoints.json")))
    out = []
    for line in open(os.path.join(ROOT, "assets/icons.txt")):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if line not in cp:
            sys.exit(f"icons.txt: unknown Lucide icon '{line}'")
        out.append((line, cp[line]))
    return out


def camel(name):
    return "".join(p.capitalize() for p in name.split("-"))


def cname(fid):
    return "k" + "".join(p.capitalize() for p in fid.split("_"))


def patch_cmap(data, name):
    """M5GFX 0.3.0 (BFFfont) reads cmap data offsets as relative to the cmap *payload*, but
    lv_font_conv writes them relative to the cmap *record* (8 bytes earlier). The loader tries to
    guess which one a font uses and guesses wrong for small tables. Make the offsets payload
    relative for every subtable that carries data (format 0, 1 and 3; format 2 has none), which
    the loader then reads correctly whichever way its guess goes."""
    import struct

    b = bytearray(data)
    off = 0
    while off < len(b):
        size, = struct.unpack_from("<I", b, off)
        if bytes(b[off + 4:off + 8]) == b"cmap":
            n, = struct.unpack_from("<I", b, off + 8)
            for i in range(n):
                p = off + 12 + 16 * i
                do, = struct.unpack_from("<I", b, p)
                ftype = b[p + 14]
                if ftype != 2:
                    if do < 8 or do - 8 >= size - 8:
                        sys.exit(f"{name}: unexpected cmap data offset {do}")
                    struct.pack_into("<I", b, p, do - 8)
        off += size
    return bytes(b)


def emit(build):
    bins = sorted(f for f in os.listdir(build) if f.endswith(".bin"))
    hdr = ["// GENERATED by tools/gen-assets.sh. Do not edit by hand.", "#pragma once", "",
           "#include <cstddef>", "#include <cstdint>", "", "namespace pos::gen {", ""]
    src = ["// GENERATED by tools/gen-assets.sh. Do not edit by hand.", '#include "gen/fonts.h"', "",
           "namespace pos::gen {", ""]
    total = 0
    for f in bins:
        fid = f[:-4]
        data = patch_cmap(open(os.path.join(build, f), "rb").read(), f)
        total += len(data)
        n = cname(fid)
        hdr.append(f"extern const uint8_t {n}[];  // {len(data)} bytes")
        hdr.append(f"constexpr size_t {n}Size = {len(data)};")
        rows = []
        for i in range(0, len(data), 32):
            rows.append(",".join(str(b) for b in data[i:i + 32]))
        src.append(f"const uint8_t {n}[] = {{")
        src.append(",\n".join(rows))
        src.append("};\n")
    hdr += ["", f"constexpr size_t kTotalFontBytes = {total};", "", "}  // namespace pos::gen", ""]
    src += ["}  // namespace pos::gen", ""]
    open(os.path.join(ROOT, "src/gen/fonts.h"), "w").write("\n".join(hdr))
    open(os.path.join(ROOT, "src/gen/fonts.cpp"), "w").write("\n".join(src))

    ic = icons()
    h = ["// GENERATED by tools/gen-assets.sh from assets/icons.txt. Do not edit by hand.", "#pragma once", "",
         "#include <cstdint>", "", "namespace pos::gen {", "", "enum class Icon : uint8_t {"]
    h += [f"  {camel(n)}," for n, _ in ic]
    h += ["  Count", "};", "", "// Unicode code point of each icon in the Lucide icon fonts (index = Icon).",
          "constexpr uint32_t kIconCodepoint[] = {"]
    h += [f"  0x{c:04X},  // {n}" for n, c in ic]
    h += ["};", "", "}  // namespace pos::gen", ""]
    open(os.path.join(ROOT, "src/gen/icons.h"), "w").write("\n".join(h))
    print(f"fonts: {len(bins)} blobs, {total} bytes; icons: {len(ic)}")


if __name__ == "__main__":
    if sys.argv[1] == "icon-ranges":
        print(",".join(f"0x{c:X}" for _, c in icons()))
    elif sys.argv[1] == "emit":
        emit(sys.argv[2])
