#!/usr/bin/env python3
"""Writes src/apps/wordgame/words_data.cpp from assets/wordgame/answers.txt and extra.txt (docs/apps/wordgame.md "Words").

  python3 tools/gen-wordgame-words.py            write the file
  python3 tools/gen-wordgame-words.py --check    fail if the file is not what the lists give (make check does not run this)
  python3 tools/gen-wordgame-words.py --day N    print the word of day N (0 = 2026-11-16), for writing tests

The dictionary is every word of both lists, sorted. The words of the day are the answers in a fixed shuffled order (own
xorshift, so the order never depends on the Python version), stored as indices into the dictionary: nobody reads next
week's words by opening the source file.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SEED = 0x5EED2026


def read(name):
    words = []
    for line in (ROOT / "assets" / "wordgame" / name).read_text(encoding="utf-8").splitlines():
        words += line.split("#", 1)[0].split()
    bad = [w for w in words if not re.fullmatch(r"[a-z]{5}", w)]
    if bad:
        sys.exit(f"{name}: not five letters a-z: {' '.join(bad)}")
    return words


def shuffled(words):
    out = sorted(set(words))
    state = SEED
    for i in range(len(out) - 1, 0, -1):
        state ^= (state << 13) & 0xFFFFFFFF
        state ^= state >> 17
        state ^= (state << 5) & 0xFFFFFFFF
        j = state % (i + 1)
        out[i], out[j] = out[j], out[i]
    return out


def build():
    answers = read("answers.txt")
    extra = read("extra.txt")
    twice = sorted({w for w in answers if answers.count(w) > 1})
    if twice:
        sys.exit(f"answers.txt: listed twice: {' '.join(twice)}")
    words = sorted(set(answers) | set(extra))
    order = shuffled(answers)
    index = {w: i for i, w in enumerate(words)}
    lines = [
        "// Generated by tools/gen-wordgame-words.py from assets/wordgame/answers.txt and extra.txt. Do not edit.",
        '#include "apps/wordgame/wordgame.h"',
        "",
        "namespace pos::wordgame::data {",
        "",
        f"const int kWordCount = {len(words)};",
        "// Every accepted word, sorted, five letters each, no separators.",
        "const char kWords[] =",
    ]
    per = 20
    for i in range(0, len(words), per):
        lines.append('    "' + "".join(words[i:i + per]) + '"')
    lines[-1] += ";"
    lines += [
        "",
        f"const int kAnswerCount = {len(order)};",
        "// The word of each day, as an index into kWords.",
        "const uint16_t kAnswers[] = {",
    ]
    ids = [index[w] for w in order]
    for i in range(0, len(ids), per):
        lines.append("    " + ", ".join(str(n) for n in ids[i:i + per]) + ",")
    lines += ["};", "", "}  // namespace pos::wordgame::data", ""]
    return "\n".join(lines), words, order


def main():
    text, words, order = build()
    out = ROOT / "src" / "apps" / "wordgame" / "words_data.cpp"
    if "--day" in sys.argv:
        n = int(sys.argv[sys.argv.index("--day") + 1])
        print(order[n % len(order)])
        return
    if "--check" in sys.argv:
        if not out.exists() or out.read_text(encoding="utf-8") != text:
            sys.exit(f"{out.relative_to(ROOT)} is stale: run tools/gen-wordgame-words.py")
        print("words_data.cpp is up to date")
        return
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print(f"{out.relative_to(ROOT)}: {len(words)} words, {len(order)} answers")


if __name__ == "__main__":
    main()
